CREATE TABLE Documentos (
    DocumentoId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Tipo VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE Ciudades (
    CiudadId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Ciudad VARCHAR(255) NOT NULL
);

CREATE TABLE Categorias (
    CategoriaId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL,
    Slug VARCHAR(250) NOT NULL,
    Descripcion CLOB,
    ImagenUrl VARCHAR(255) NOT NULL,
    Estado VARCHAR(20) DEFAULT 'Activo' NOT NULL,
    FechaCreacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE Roles (
    IdRol INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Rol VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE Empleados (
    EmpleadoId INT PRIMARY KEY,
    DocumentoId INT NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    IdRol INT NOT NULL,
    Estado VARCHAR(20) DEFAULT 'Activo' NOT NULL,
    Telefono VARCHAR(20),
    Correo VARCHAR(100) NOT NULL UNIQUE,
    ContrasenaHash VARCHAR(255),
    FOREIGN KEY (DocumentoId) REFERENCES Documentos (DocumentoId),
    FOREIGN KEY (IdRol) REFERENCES Roles (IdRol)
);

CREATE TABLE Usuarios (
    UsuarioId INT PRIMARY KEY,
    DocumentoId INT NOT NULL,
    CiudadId INT NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    Direccion VARCHAR(150) NOT NULL,
    Telefono VARCHAR(20) NOT NULL,
    Correo VARCHAR(100) NOT NULL UNIQUE,
    FechaNacimiento DATE NOT NULL,
    FechaRegistro TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FOREIGN KEY (DocumentoId) REFERENCES Documentos (DocumentoId),
    FOREIGN KEY (CiudadId) REFERENCES Ciudades (CiudadId)
);

CREATE TABLE CredencialesUsuarios (
    UsuarioId INT PRIMARY KEY,
    ContrasenaHash VARCHAR(255) NOT NULL,
    FOREIGN KEY (UsuarioId) REFERENCES Usuarios (UsuarioId)
);

CREATE TABLE InsumosMenores (
    InsumoId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL,
    Referencia VARCHAR(50) NOT NULL UNIQUE,
    UnidadMedida VARCHAR(30) NOT NULL,
    CostoUnitario DECIMAL(10, 2) NOT NULL,
    CantidadDisponible DECIMAL(10, 2) NOT NULL,
    CONSTRAINT CK_InsumosMenores_Costo CHECK (CostoUnitario >= 0),
    CONSTRAINT CK_InsumosMenores_Cantidad CHECK (CantidadDisponible >= 0)
);

CREATE TABLE Productos (
    ProductoId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CategoriaId INT NOT NULL,
    EmpleadoId INT NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    Slug VARCHAR(100) NOT NULL,
    Descripcion CLOB,
    Costo DECIMAL(10, 2) NOT NULL,
    ImagenUrl VARCHAR(255) NOT NULL,
    Existencias INT DEFAULT 0 NOT NULL,
    Destacado BOOLEAN DEFAULT FALSE NOT NULL,
    FechaCreacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FechaActualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_Productos_Categorias FOREIGN KEY (CategoriaId) REFERENCES Categorias (CategoriaId),
    CONSTRAINT FK_Productos_Empleados FOREIGN KEY (EmpleadoId) REFERENCES Empleados (EmpleadoId)
);

CREATE TABLE CatalogoTallas (
    TallaId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Codigo VARCHAR(20) NOT NULL,
    NombreDescriptivo VARCHAR(100) NOT NULL,
    Sistema VARCHAR(30) NOT NULL,
    OrdenVisual INT NOT NULL,
    Estado VARCHAR(20) DEFAULT 'Activo' NOT NULL,
    CONSTRAINT UQ_CatalogoTallas_Codigo_Sistema UNIQUE (Codigo, Sistema)
);

CREATE TABLE ProductoTallas (
    ProductoTallaId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductoId INT NOT NULL,
    TallaId INT NOT NULL,
    CONSTRAINT UQ_ProductoTallas_Producto_Talla UNIQUE (ProductoId, TallaId),
    FOREIGN KEY (ProductoId) REFERENCES Productos (ProductoId),
    FOREIGN KEY (TallaId) REFERENCES CatalogoTallas (TallaId)
);

CREATE TABLE Colores (
    ColorId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductoId INT NOT NULL,
    Nombre VARCHAR(50) NOT NULL,
    CodigoHex VARCHAR(7) DEFAULT '#14B8A6' NOT NULL,
    FOREIGN KEY (ProductoId) REFERENCES Productos (ProductoId)
);

CREATE TABLE Pedidos (
    PedidoId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UsuarioId INT,
    FechaCreacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    Estado VARCHAR(50) DEFAULT 'Generado',
    FOREIGN KEY (UsuarioId) REFERENCES Usuarios (UsuarioId)
);

CREATE TABLE DetallePedido (
    PedidoId INT NOT NULL,
    ProductoId INT NOT NULL,
    Cantidad INT NOT NULL,
    Costo DECIMAL(10, 2) NOT NULL,
    FOREIGN KEY (PedidoId) REFERENCES Pedidos (PedidoId),
    FOREIGN KEY (ProductoId) REFERENCES Productos (ProductoId)
);
